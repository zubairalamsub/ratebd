// Writes dist/_redirects so that /go/{provider} sends visitors to the provider through Cloudflare Pages'
// edge redirects (no JavaScript, no server). Targets come from src/config/providers.json: the affiliate URL
// when one is configured, otherwise the provider's official homepage.
import { readFile, writeFile } from "node:fs/promises";

/** @returns {import("astro").AstroIntegration} */
export function goRedirects() {
  return {
    name: "ratebd:go-redirects",
    hooks: {
      "astro:build:done": async ({ dir, logger }) => {
        const config = JSON.parse(
          await readFile(new URL("../src/config/providers.json", import.meta.url), "utf8"),
        );
        const lines = config.providers.map((p) => {
          const target = p.affiliateUrl || p.homepage;
          if (!/^https:\/\//.test(target)) {
            throw new Error(`Provider ${p.slug} needs an https homepage or affiliateUrl`);
          }
          return `/go/${p.slug} ${target} 302`;
        });
        const body =
          "# Generated by integrations/go-redirects.mjs from src/config/providers.json\n" +
          lines.join("\n") +
          "\n";
        await writeFile(new URL("_redirects", dir), body, "utf8");
        logger.info(`wrote ${lines.length} /go redirects`);
      },
    },
  };
}
